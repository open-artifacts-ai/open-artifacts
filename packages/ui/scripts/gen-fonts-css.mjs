// Writes src/tokens/fonts.css: the Geist 400/500/600 and Geist Mono 400/500
// faces, woff2 only, from @fontsource's files, with its per-subset
// unicode-ranges (the browser fetches only the subsets a page uses, as it did
// from Google Fonts). Run: node scripts/gen-fonts-css.mjs, then biome format.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const pkg = (name) => dirname(require.resolve(`${name}/package.json`));

const FACES = [
  {
    name: "@fontsource/geist",
    family: "Geist",
    file: "geist",
    weights: [400, 500, 600],
  },
  {
    name: "@fontsource/geist-mono",
    family: "Geist Mono",
    file: "geist-mono",
    weights: [400, 500],
  },
];

let out = `/*
 * Self-hosted Geist (Geist 400/500/600, Geist Mono 400/500), woff2 only, from
 * @fontsource/geist and @fontsource/geist-mono (SIL OFL). Generated by
 * scripts/gen-fonts-css.mjs; do not edit by hand. No third-party host.
 */
`;
for (const f of FACES) {
  const dir = pkg(f.name);
  // subset -> unicode-range, from the 400 stylesheet (identical across weights)
  const css = readFileSync(join(dir, "400.css"), "utf8");
  const ranges = [
    ...css.matchAll(
      new RegExp(
        `/\\* ${f.file}-([a-z-]+)-400-normal \\*/[\\s\\S]*?unicode-range: ([^;]+);`,
        "g",
      ),
    ),
  ].map((m) => [m[1], m[2]]);
  for (const w of f.weights)
    for (const [subset, range] of ranges)
      out += `@font-face {
  font-family: "${f.family}";
  font-style: normal;
  font-display: swap;
  font-weight: ${w};
  src: url("${f.name}/files/${f.file}-${subset}-${w}-normal.woff2") format("woff2");
  unicode-range: ${range};
}
`;
}
writeFileSync(join(import.meta.dirname, "../src/tokens/fonts.css"), out);
console.log(`fonts.css: ${(out.match(/@font-face/g) ?? []).length} faces`);
