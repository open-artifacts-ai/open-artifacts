// Writes src/version.gen.ts (VERSION, COMMIT, SKILL_COMMAND_MIN_BUS) from the root package.json and
// git, by the rule in scripts/version-rule.ts. The file is gitignored: the
// package's build, test, test:cpu, bench and typecheck scripts run this first,
// so every deploy, bundle and test sees it. Writes only on change. BUS_PKG is
// the verified release pin of the bus package (scripts/bus-pin.ts), written
// only with --pin; null otherwise.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { resolvePin, resolvePinWithFallback } from "./bus-pin.ts";
import { firstReleaseCiting } from "./skill-min-bus.ts";
import { instanceVersion } from "./version-rule.ts";

const root = path.join(import.meta.dirname, "..", "..", "..");
const out = path.join(import.meta.dirname, "..", "src", "version.gen.ts");

const git = (args: string[]): string | null => {
  try {
    return execFileSync("git", args, {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    return null;
  }
};

const { version } = JSON.parse(
  readFileSync(path.join(root, "package.json"), "utf8"),
) as { version: string };
const sha = git(["rev-parse", "--short=7", "HEAD"]) || null;
const tagOut = sha ? git(["tag", "--points-at", "HEAD"]) : null;
const tags = tagOut === null ? null : tagOut.split("\n").filter(Boolean);
const v = instanceVersion({ version, tags, sha });
// The release pin of @open-artifacts/bus (#2543): only with --pin (the build
// scripts), never in tests or CI, since it asks the registry. It is verified
// the way the updater verifies a release, and printed for reviewers.
let busPkg: { version: string; integrity: string } | null = null;
let busPkgFallbackFor: string | null = null;
let busPkgWhy = "this build was not asked to verify a bus release";
if (process.argv.includes("--pin")) {
  // The release run (BUS_PIN_REQUIRED=1) cannot ship without a pin; a dev or
  // self-built server keeps the no-pin text.
  const required = process.env.BUS_PIN_REQUIRED === "1";
  const r = required
    ? await resolvePinWithFallback(v, {}, { log: console.log })
    : await resolvePin(v);
  console.log(r.log);
  if (required && r.pin === null) {
    console.error(`bus pin required but missing: ${r.why}`);
    process.exit(1);
  }
  busPkg = r.pin;
  busPkgWhy = r.why;
  if (r.pin !== null && r.fallbackFor !== undefined)
    busPkgFallbackFor = r.fallbackFor;
}
// The first bus release with `oa-bus skill` (#2624): read from the CHANGELOG.
const changelogPath = path.join(root, "CHANGELOG.md");
const changelog = existsSync(changelogPath)
  ? readFileSync(changelogPath, "utf8")
  : "";
const skillMin = firstReleaseCiting(changelog, "#2624");
const releases = [...changelog.matchAll(/^## \[(\d+\.\d+\.\d+)\]/gm)].map(
  (match) => match[1],
);
const index = releases.indexOf(v);
const previous = index >= 0 ? (releases[index + 1] ?? null) : null;
const body = `// Generated by scripts/emit-version.ts. Do not edit.
export const VERSION = ${JSON.stringify(v)};
export const PREVIOUS_RELEASE: string | null = ${JSON.stringify(previous)};
export const COMMIT = ${JSON.stringify(sha ?? "")};
export const BUS_PKG: { version: string; integrity: string } | null = ${JSON.stringify(busPkg)};
export const BUS_PKG_WHY = ${JSON.stringify(busPkgWhy)};
export const BUS_PKG_FALLBACK_FOR: string | null = ${JSON.stringify(busPkgFallbackFor)};
export const SKILL_COMMAND_MIN_BUS: string | null = ${JSON.stringify(skillMin)};
`;
if (!existsSync(out) || readFileSync(out, "utf8") !== body)
  writeFileSync(out, body);
console.log(`version ${v}`);
