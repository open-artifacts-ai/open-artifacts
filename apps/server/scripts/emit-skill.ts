// Writes src/mcp/skill.generated.ts: the /skill.md core and /skill/<part>.md
// templates rendered from TOOL_DEFS and the INSTRUCTIONS sections, with
// {{tokens}} for the per-instance values. Gitignored: `pnpm gen` writes it,
// and the package's build, test, test:cpu, bench and typecheck scripts run that
// first.
import { createHash } from "node:crypto";
import path from "node:path";
import {
  renderSkillPartTemplate,
  renderSkillTemplate,
  SKILL_PARTS,
  type SkillPart,
} from "../src/mcp/skill-template.ts";
import { writeGenerated } from "./write-generated.ts";

const out = path.join(
  import.meta.dirname,
  "..",
  "src",
  "mcp",
  "skill.generated.ts",
);
const tpl = renderSkillTemplate();
// Without the spaces feature: no spaces lines (parity 1).
const noSpaces = renderSkillTemplate(false);
/** In the ETag, so a template change is a new ETag even at the same VERSION. */
const hashOf = (t: string) =>
  createHash("sha256").update(t).digest("hex").slice(0, 8);
// A template literal keeps the file readable and stable under the formatter.
const literal = (t: string) =>
  t.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

// #3169: on-demand skill parts, both spaces variants.
const emitPartMap = (spaces: boolean) => {
  const entries = SKILL_PARTS.map((p: SkillPart) => {
    const body = renderSkillPartTemplate(p, spaces);
    return [p, body, hashOf(body)] as const;
  });
  const hashes = entries
    .map(([p, , h]) => `  ${JSON.stringify(p)}: "${h}",`)
    .join("\n");
  const templates = entries
    .map(([p, body]) => `  ${JSON.stringify(p)}: \`${literal(body)}\`,`)
    .join("\n");
  return { hashes, templates };
};

const parts = emitPartMap(true);
const partsNoSpaces = emitPartMap(false);

writeGenerated(
  out,
  `// Generated by scripts/emit-skill.ts from src/mcp/skill-template.ts. Do not edit.
import type { SkillPart } from "./skill-template.js";

export const SKILL_HASH = "${hashOf(tpl)}";
export const SKILL_TEMPLATE = \`${literal(tpl)}\`;
export const SKILL_HASH_NO_SPACES = "${hashOf(noSpaces)}";
export const SKILL_TEMPLATE_NO_SPACES = \`${literal(noSpaces)}\`;
export const SKILL_PART_HASHES: Record<SkillPart, string> = {
${parts.hashes}
};
export const SKILL_PART_TEMPLATES: Record<SkillPart, string> = {
${parts.templates}
};
export const SKILL_PART_HASHES_NO_SPACES: Record<SkillPart, string> = {
${partsNoSpaces.hashes}
};
export const SKILL_PART_TEMPLATES_NO_SPACES: Record<SkillPart, string> = {
${partsNoSpaces.templates}
};
`,
);
console.log(
  `wrote skill templates (core ${tpl.split("\n").length} lines, ${SKILL_PARTS.length} parts) to ${path.relative(process.cwd(), out)}`,
);
