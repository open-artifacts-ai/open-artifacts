// Writes src/mcp/skill.generated.ts: the /skill.md template rendered from
// TOOL_DEFS and the INSTRUCTIONS sections, with {{tokens}} for the
// per-instance values. Gitignored: `pnpm gen` writes it, and the package's
// build, test, test:cpu, bench and typecheck scripts run that first.
import { createHash } from "node:crypto";
import path from "node:path";
import { renderSkillTemplate } from "../src/mcp/skill-template.ts";
import { writeGenerated } from "./write-generated.ts";

const out = path.join(
  import.meta.dirname,
  "..",
  "src",
  "mcp",
  "skill.generated.ts",
);
const tpl = renderSkillTemplate();
// Without the spaces feature: no spaces lines (parity 1).
const noSpaces = renderSkillTemplate(false);
/** In the ETag, so a template change is a new ETag even at the same VERSION. */
const hashOf = (t: string) =>
  createHash("sha256").update(t).digest("hex").slice(0, 8);
// A template literal keeps the file readable and stable under the formatter.
const literal = (t: string) =>
  t.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
writeGenerated(
  out,
  `// Generated by scripts/emit-skill.ts from src/mcp/skill-template.ts. Do not edit.\nexport const SKILL_HASH = "${hashOf(tpl)}";\nexport const SKILL_TEMPLATE = \`${literal(tpl)}\`;\nexport const SKILL_HASH_NO_SPACES = "${hashOf(noSpaces)}";\nexport const SKILL_TEMPLATE_NO_SPACES = \`${literal(noSpaces)}\`;\n`,
);
console.log(
  `wrote skill template (${tpl.split("\n").length} lines) to ${path.relative(process.cwd(), out)}`,
);
