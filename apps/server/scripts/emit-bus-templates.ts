// Writes src/bus/page-template.ts from Design's design/screens/bus.html,
// bus-revoke.html and bus-snippets/*.html (each top comment stripped), so the
// Worker bundles them as strings. Run by `pnpm build`; the file is committed
// and test/bus.page.test.ts fails when it is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { busSnippetOf, stripTemplateComment } from "../src/mcp/template.ts";

const root = path.join(import.meta.dirname, "..");
const screens = path.join(root, "..", "..", "design", "screens");
const out = path.join(root, "src", "bus", "page-template.ts");

// A template literal keeps the file readable and stable under the formatter.
const literal = (s: string) =>
  `\`${s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")}\``;
const page = (f: string) =>
  stripTemplateComment(readFileSync(path.join(screens, f), "utf8"));

const dir = path.join(screens, "bus-snippets");
const snippets = readdirSync(dir)
  .filter((f) => f.endsWith(".html"))
  .sort()
  .map(
    (f) =>
      `  "${f.slice(0, -5)}": ${literal(busSnippetOf(readFileSync(path.join(dir, f), "utf8")))},`,
  )
  .join("\n");

writeFileSync(
  out,
  `// Generated by scripts/emit-bus-templates.ts from design/screens/bus.html, bus-revoke.html and bus-snippets/. Do not edit.
export const BUS_PAGE_TEMPLATE = ${literal(page("bus.html"))};
export const BUS_REVOKE_TEMPLATE = ${literal(page("bus-revoke.html"))};
export const BUS_SNIPPETS = {
${snippets}
} as const;
`,
);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
